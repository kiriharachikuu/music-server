-- ============================================================
-- 清理 9 档排行榜精简为 3 档后的孤儿系统歌单
-- ============================================================
-- 背景：原实现维护 9 档榜单（3 分类 × 3 类别：综合 / 单曲 / 歌切），
--       系统歌单随之也是 9 个。
--       现仅保留 3 档"综合"榜单（综合-飙升榜 / 综合-热歌榜 / 综合-新歌榜），
--       另 6 个"单曲-* / 歌切-*"系统歌单不再被 RankingPlaylistService 维护。
--
-- 策略：软删除（设置 deletedAt），保留数据以便回滚或人工审计；
--       若后续需要硬删除，可单独再发一个 migration。
--       软删除的记录会被现有列表查询（WHERE deletedAt IS NULL）自动过滤，
--       用户在前端歌单列表里看不到，但数据库里仍可追溯。
-- ============================================================

UPDATE "Playlist"
SET "deletedAt" = CURRENT_TIMESTAMP
WHERE "isSystem" = 1
  AND "deletedAt" IS NULL
  AND "name" IN (
    '单曲-飙升榜',
    '单曲-热歌榜',
    '单曲-新歌榜',
    '歌切-飙升榜',
    '歌切-热歌榜',
    '歌切-新歌榜'
  );
